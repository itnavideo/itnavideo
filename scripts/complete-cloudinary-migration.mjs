import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { pipeline } from 'node:stream/promises';
import { createWriteStream } from 'node:fs';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT_DIR = join(__dirname, '..');

const BUCKET_NAME = 'itnavideo-media-assets';
const TEMP_DIR = join(ROOT_DIR, 'tmp-complete-migration');

// Scan all relevant folders
const SCAN_FOLDERS = ['components', 'lib', 'app', 'constants', 'remotion', 'services'];
const EXCLUDE_PATTERNS = [/node_modules/, /\.next/, /\.git/, /tmp-complete-migration/];

function getAllFiles(dir, files = []) {
  if (!existsSync(dir)) return files;
  const list = readdirSync(dir);
  for (const item of list) {
    const fullPath = join(dir, item);
    if (EXCLUDE_PATTERNS.some(pattern => pattern.test(fullPath))) continue;
    
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      getAllFiles(fullPath, files);
    } else {
      const ext = extname(fullPath).toLowerCase();
      if (['.ts', '.tsx', '.json', '.js', '.jsx', '.css', '.html'].includes(ext)) {
        files.push(fullPath);
      }
    }
  }
  return files;
}

function parseCloudinaryUrl(url) {
  // Matches typical res.cloudinary.com URLs, extracting resource type and trailing key path
  const regex = /https:\/\/res\.cloudinary\.com\/dhouh9idx\/(image|video)\/upload\/(?:[^\/]+\/)?(?:v\d+\/)?([^\s"'\)\};,]+)/;
  const match = url.match(regex);
  if (!match) return null;
  return {
    type: match[1],
    relativePath: match[2],
  };
}

async function downloadFile(url, destPath) {
  const dir = dirname(destPath);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to download ${url}: ${response.statusText}`);
  }
  const fileStream = createWriteStream(destPath);
  await pipeline(response.body, fileStream);
}

async function startMigration() {
  console.log('[MIGRATION] Starting complete Cloudinary to GCS downloader & code rewriter...');
  
  if (!existsSync(TEMP_DIR)) {
    mkdirSync(TEMP_DIR, { recursive: true });
  }

  // 1. Gather all files in scope
  const allFiles = [];
  for (const folder of SCAN_FOLDERS) {
    getAllFiles(join(ROOT_DIR, folder), allFiles);
  }
  console.log(`[MIGRATION] Scanned ${allFiles.length} files.`);

  // 2. Extract unique Cloudinary URLs
  const cloudinaryUrls = new Set();
  const urlRegex = /https:\/\/res\.cloudinary\.com\/dhouh9idx\/[a-zA-Z0-9_\-\.\/%+@!]+/g;

  for (const file of allFiles) {
    // Skip reading migration scripts themselves
    if (file.includes('migrate-cloudinary-to-gcs.mjs') || file.includes('complete-cloudinary-migration.mjs')) {
      continue;
    }
    const content = readFileSync(file, 'utf8');
    const matches = content.match(urlRegex);
    if (matches) {
      for (const match of matches) {
        // Clean trailing symbols often captured by regex
        const cleanUrl = match.replace(/['"\)\}\s,;]+$/, '');
        cloudinaryUrls.add(cleanUrl);
      }
    }
  }

  console.log(`[MIGRATION] Found ${cloudinaryUrls.size} unique Cloudinary URLs.`);
  
  const migrationMap = {}; // originalUrl -> GCS url

  // 3. Process and download each unique URL
  for (const rawUrl of cloudinaryUrls) {
    try {
      const parsed = parseCloudinaryUrl(rawUrl);
      if (!parsed) {
        console.warn(`[MIGRATION] Skipping unparsable URL: ${rawUrl}`);
        continue;
      }

      const { type, relativePath } = parsed;
      
      // Standardize GCS path (convert %20, spaces, and make lowercase/safe where appropriate)
      const sanitizedPath = relativePath.replace(/%20/g, '-').replace(/\s+/g, '-');
      const gcsUrl = `https://storage.googleapis.com/${BUCKET_NAME}/${sanitizedPath}`;
      
      console.log(`\n[MIGRATION] Processing: ${rawUrl}`);
      console.log(`  ➔ Target GCS: ${gcsUrl}`);

      const localDest = join(TEMP_DIR, sanitizedPath);

      // Download raw asset from Cloudinary
      console.log(`  ➔ Downloading raw asset...`);
      await downloadFile(rawUrl, localDest);
      console.log(`  ➔ Downloaded to: ${localDest}`);

      migrationMap[rawUrl] = gcsUrl;

      // Handle video posters pre-generated by Cloudinary on-the-fly
      if (type === 'video' && (rawUrl.endsWith('.mp4') || rawUrl.endsWith('.webm') || rawUrl.includes('/video/upload/'))) {
        const posterRelPath = sanitizedPath.replace(/\.(mp4|webm)$/i, '.jpg');
        const posterGcsUrl = `https://storage.googleapis.com/${BUCKET_NAME}/${posterRelPath}`;

        // Generate the Cloudinary transform URL for poster
        const cloudinaryPosterUrl = rawUrl
          .replace(/\/video\/upload\/(?:[^\/]+\/)?(?:v\d+\/)?/g, '/video/upload/f_auto,q_auto,w_600,so_1/')
          .replace(/\.(mp4|webm)$/i, '.jpg');

        const localPosterDest = join(TEMP_DIR, posterRelPath);
        
        try {
          console.log(`  ➔ Video detected. Fetching auto-poster: ${cloudinaryPosterUrl}`);
          await downloadFile(cloudinaryPosterUrl, localPosterDest);
          console.log(`  ➔ Downloaded poster to: ${localPosterDest}`);

          // Map any potential variations
          const directPosterUrl = rawUrl.replace(/\.(mp4|webm)$/i, '.jpg');
          migrationMap[directPosterUrl] = posterGcsUrl;
          migrationMap[cloudinaryPosterUrl] = posterGcsUrl;
        } catch (posterErr) {
          console.warn(`  ➔ [WARNING] Could not fetch auto-poster for ${rawUrl}: ${posterErr.message}`);
        }
      }

    } catch (err) {
      console.error(`  ➔ [ERROR] Failed to migrate ${rawUrl}:`, err.message);
    }
  }

  // 4. Update references across the entire codebase
  console.log('\n[MIGRATION] Rewriting code references to GCS URLs...');
  let updatedFilesCount = 0;

  for (const file of allFiles) {
    if (file.includes('migrate-cloudinary-to-gcs.mjs') || file.includes('complete-cloudinary-migration.mjs')) {
      continue;
    }
    
    let content = readFileSync(file, 'utf8');
    let hasChanged = false;

    // Direct replacement of exact mapped URLs
    for (const [cloudinaryUrl, gcsUrl] of Object.entries(migrationMap)) {
      if (content.includes(cloudinaryUrl)) {
        content = content.replaceAll(cloudinaryUrl, gcsUrl);
        hasChanged = true;
      }
    }

    // Generic fallback regex replacement for remaining/hidden patterns
    if (content.includes('https://res.cloudinary.com/dhouh9idx/')) {
      const matchRegex = /https:\/\/res\.cloudinary\.com\/dhouh9idx\/(image|video)\/upload\/(?:[^\/]+\/)?(?:v\d+\/)?([^\s"'\)\};,]+)/g;
      content = content.replace(matchRegex, (match, type, relPath) => {
        const sanitizedRelPath = relPath.replace(/['"\)\}\s,;]+$/, '').replace(/%20/g, '-').replace(/\s+/g, '-');
        const finalUrl = `https://storage.googleapis.com/${BUCKET_NAME}/${sanitizedRelPath}`;
        console.log(`[GENERIC_REWRITE] Rewrote: ${match} ➔ ${finalUrl}`);
        hasChanged = true;
        return finalUrl;
      });
    }

    if (hasChanged) {
      writeFileSync(file, content, 'utf8');
      console.log(`[MIGRATION] Updated file: ${file.replace(ROOT_DIR, '')}`);
      updatedFilesCount++;
    }
  }

  console.log(`\n[MIGRATION] Successfully updated ${updatedFilesCount} files.`);
  console.log('[MIGRATION] Code references updated. Please run gsutil or gcloud command to upload downloads to GCS bucket!\n');
}

startMigration().catch(err => {
  console.error('[MIGRATION] Fatal migration error:', err);
});
